-- 회원 계정
create table accounts (
    id             bigint generated by default as identity primary key,
    username       varchar(20)  not null,
    password_hash  varchar(100) not null,
    email          varchar(254) not null,          -- 소문자로 저장
    email_verified boolean      not null default false,
    role           varchar(20)  not null,          -- USER | ADMIN
    google_sub     varchar(255),                   -- 연동된 구글 계정 ID (OIDC sub)
    google_email   varchar(254),
    created_at     timestamp with time zone not null,
    last_login_at  timestamp with time zone,
    constraint uk_accounts_username unique (username),
    constraint uk_accounts_email unique (email),
    constraint uk_accounts_google_sub unique (google_sub)
);

-- 이메일 인증번호 (계정당 하나, 인증되면 지운다)
create table email_verifications (
    account_id bigint primary key,
    code_hash  varchar(64) not null,               -- SHA-256(계정 ID:인증번호)
    expires_at timestamp with time zone not null,
    sent_at    timestamp with time zone not null,
    attempts   integer not null default 0,
    constraint fk_email_verifications_account foreign key (account_id) references accounts (id) on delete cascade
);
